"""Builds index.html from the series template (videos/mcd-part2/index.html), common-props.js and scenes.js.
Run from videos/mako-knee: python3 build.py"""
import re
tpl = open('../mcd-part2/index.html', encoding='utf-8').read()
head, tail = tpl[:tpl.index('// ---------- extra props ----------')], tpl[tpl.index('function renderFrame(t)'):]
head = head[:head.index('// ---------- timing')] + head[head.index('// ---------- text ----------'):]
a = head.index('// «Маркетинговые кейсы»'); b = head.index('// ------------------------------------------------------------------------------------------\nconst W')
props = open('common-props.js', encoding='utf-8').read()
for d, title, note in (('.', 'Mako Knee Reel', 'Эндопротезирование колена на роботе Mako — dr_bulat_'),):
    scenes = open(f'{d}/scenes.js', encoding='utf-8').read()
    h = head[:a] + f"// «{note}». Generated by videos/mako-knee/build.py — edit scenes.js or common-props.js.\n// Flat vector explainer in the client's look: dark brown + gold; red = pain, green = robot safe zone. Deterministic: renderFrame(t).\n" + head[b:]
    h = h.replace('<title>Monopoly Case Reel 2</title>', f'<title>{title}</title>')
    h = re.sub(r"ctx\.fillText\('МАРКЕТИНГОВЫЕ КЕЙСЫ · ЧАСТЬ 2', 70, 190\);", "ctx.fillText(LABEL, 70, 190);", h)
    tail2 = tail.replace("document.fonts.load(font(800, 60), 'АБВ')", "document.fonts.load(font(800, 60), 'АБВ'), document.fonts.load('900 60px \"Playfair Display\"', 'KERIM')")
    assert tail2 != tail
    h = re.sub(r"const BG = '#[0-9a-f]+', BG2 = '#[0-9a-f]+', YEL = '#[0-9a-f]+'", "const BG = '#120d08', BG2 = '#241a10', YEL = '#e2b866'", h)
    assert "'#e2b866'" in h
    tail2 = tail2.replace("'KERIM')", "'MAKO'), docImg.decode().catch(() => {})")
    assert 'docImg.decode' in tail2
    open(f'{d}/index.html', 'w', encoding='utf-8').write(h + props + '\n' + scenes + '\n' + tail2)
    print(d, 'ok')
