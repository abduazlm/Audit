"""Builds fraud/index.html and debts/index.html from the series template (videos/mcd-part2/index.html),
common-props.js and each reel's scenes.js. Run from videos/law: python3 build.py"""
import re
tpl = open('../mcd-part2/index.html', encoding='utf-8').read()
head, tail = tpl[:tpl.index('// ---------- extra props ----------')], tpl[tpl.index('function renderFrame(t)'):]
head = head[:head.index('// ---------- timing')] + head[head.index('// ---------- text ----------'):]
a = head.index('// «Маркетинговые кейсы»'); b = head.index('// ------------------------------------------------------------------------------------------\nconst W')
props = open('common-props.js', encoding='utf-8').read()
for d, title, note in (('fraud', 'Online Fraud Reel', 'Интернет-мошенничество: первые 24 часа'),
                       ('debts', 'Solvency Restoration Reel', 'Восстановление платёжеспособности: долги по графику до 5 лет')):
    scenes = open(f'{d}/scenes.js', encoding='utf-8').read()
    h = head[:a] + f"// Юридические ролики: «{note}». Generated by videos/law/build.py — edit {d}/scenes.js or common-props.js.\n// Series style of the case reels: flat vector on dark, yellow = key words, red = threat. Deterministic: renderFrame(t).\n" + head[b:]
    h = h.replace('<title>Monopoly Case Reel 2</title>', f'<title>{title}</title>')
    h = re.sub(r"ctx\.fillText\('МАРКЕТИНГОВЫЕ КЕЙСЫ · ЧАСТЬ 2', 70, 190\);", "ctx.fillText(LABEL, 70, 190);", h)
    open(f'{d}/index.html', 'w', encoding='utf-8').write(h + props + '\n' + scenes + '\n' + tail)
    print(d, 'ok')
